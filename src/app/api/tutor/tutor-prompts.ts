/**
 * AI 同桌 / 家教 System Prompts
 *
 * 设计哲学：Less Structure, More Intelligence
 * —— 参见 `项目开发文档/提示词设计哲学.md`
 *
 * 一、核心思路
 *   提示词只描述"你是谁、学生是谁、此刻发生了什么、你在这段关系里的位置"。
 *   具体要说几句话、用什么结构、要不要追问，都留给模型自己判断。
 *   这样换更强的模型时质量自动上升，不需要重写 prompt。
 *
 * 二、不变的渲染契约（这两条是前端能解析的硬合同，不能删）
 *   1. [MM:SS] 或 [MM:SS-MM:SS] —— 前端会渲染为可点击跳转的时间戳链接
 *      （也兼容旧的 [引用 mm:ss] 写法，但新 prompt 不再强推这种格式）
 *   2. [资料N] —— 引用 support material 时使用现有编号，不得编造
 *
 * 三、两层结构（每个 prompt 都遵守这个骨架）
 *   第一层：你在这个学生身边是什么角色（可进化）
 *   第二层：渲染契约（上面那两条，用最精简的语气提一次）
 *
 * 四、本文件导出的 prompt 分两家
 *   - 文字家教（走 /api/tutor 的 SSE 文本流，渲染在气泡里）
 *   - 语音同桌（走 qwen-omni 的实时语音，通过耳朵进到学生大脑里）
 *   两家共用 `COMPANION_PERSONA` 作为人格根。
 */

// ──────────────────────────────────────────────────────────────
// 共享：同桌人格根
