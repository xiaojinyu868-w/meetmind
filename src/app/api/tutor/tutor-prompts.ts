/**
 * 将学习者画像 JSON 格式化为可注入 system prompt 的文本段落。
 *
 * 设计原则（对齐"描述用户，不描述格式"）：
 * - 身份是稳定背景，不是指令——不要写死"请按研究生水平解释"
 * - 学习是多线程的——一个 NLP 研究生也可能在学英语
 * - 当前内容才是主角——MeetMind 看得到用户发进来的是什么
 * - 如果没有画像或解析失败，返回空字符串
 */
export function formatLearnerContext(profileJson: string | null | undefined): string {
  if (!profileJson) return '';
  try {
    const p = JSON.parse(profileJson) as Record<string, unknown>;
    const lines: string[] = ['【这个学生】'];

    switch (p.stage) {
      case 'k12':
        lines.push(`- ${p.gradeLevel || '中小学生'}`);
        if (p.textbookEdition) lines.push(`- 教材：${p.textbookEdition}`);
        if (Array.isArray(p.weakSubjects) && p.weakSubjects.length > 0) lines.push(`- 觉得吃力的科目：${p.weakSubjects.join('、')}`);
        break;
      case 'university':
        lines.push(`- ${p.year || '大学生'} · ${p.major || '未知专业'}`);
        if (Array.isArray(p.currentCourses) && p.currentCourses.length > 0) lines.push(`- 这学期在上：${p.currentCourses.join('、')}`);
        break;
      case 'graduate':
        lines.push(`- 研究生 · ${p.field || '未知方向'}`);
        if (p.advisor) lines.push(`- 导师：${p.advisor}`);
        if (p.researchTopic) lines.push(`- 课题：${p.researchTopic}`);
        break;
      case 'working':
        lines.push(`- 在职学习 · ${p.industry || '未知行业'}`);
        if (p.learningGoal) lines.push(`- 学习目标：${p.learningGoal}`);
        break;
      default:
        return '';
    }

    if (p.goal) lines.push(`- 最近的目标：${p.goal}`);
    if (p.otherInterests) lines.push(`- 同时也在学：${p.otherInterests}`);

    lines.push('');
    lines.push('这个学生学习是多线程的——手头这份内容可能和他上面写的主方向无关。');
    lines.push('所以以他现在递给你的课堂/材料为准来判断怎么讲，上面这些只是帮你大致估计他的底。');

    return '\n\n' + lines.join('\n');
  } catch {
    return '';
  }
}
